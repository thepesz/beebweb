// Helper type for accessing translation keys
export type TranslationKey = keyof typeof translations;

// Helper function to get a simple string translation
export function t(
  section: keyof typeof translations,
  key: string,
  locale: Locale
): string {
  const sectionData = translations[section] as Record<string, Record<Locale, unknown>>;
  const entry = sectionData?.[key];
  if (!entry) return '';
  return (entry[locale] as string) ?? '';
}
